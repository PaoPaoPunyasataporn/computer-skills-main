/** mulberry32 — tiny, fast, deterministic PRNG. Same seed => same stream. */
function mulberry32(seed: number): () => number {
  // Normalise to a 32-bit unsigned integer so any seed (negative, float) works.
  let a = seed >>> 0;
  return function next(): number {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Pick `n` distinct items from `bank`, deterministically driven by `seed`.
 * Uses a seeded partial Fisher–Yates shuffle on a copy — the bank is never mutated.
 * If n >= bank.length, the whole (shuffled) bank is returned.
 */
function pickSeeded<T>(bank: readonly T[], seed: number, n: number): T[] {
  const pool = bank.slice();
  const count = Math.max(0, Math.min(Math.floor(n), pool.length));
  const rnd = mulberry32(seed);
  for (let i = 0; i < count; i++) {
    const j = i + Math.floor(rnd() * (pool.length - i));
    const tmp = pool[i];
    pool[i] = pool[j];
    pool[j] = tmp;
  }
  return pool.slice(0, count);
}

